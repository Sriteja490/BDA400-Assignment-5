# Run from project root: source('tests.R')
for (nm in c('sma','ema','macd','stdev','linreg','rsi','stoch_rsi','crossover','crossunder')) source(file.path('scripts', paste0(nm, '.R')))
near <- function(x, y, tolerance=1e-8) isTRUE(all.equal(x, y, tolerance=tolerance))
stopifnot(near(sma(c(10,12,15,20), 3), c(37/3,47/3)))
stopifnot(near(ema(c(10,12,15), 3), c(10,11,13)))
stopifnot(near(stdev(c(2,4,4,4,5,5,7,9)), 2))
m <- macd(c(1,2,3,4,5,6), 2, 3, 2)
stopifnot(length(m$macd_line) == 6, near(m$histogram, m$macd_line - m$signal_line))
l <- linreg(c(1,3,5,7,9), 5, 0)
stopifnot(near(l$slope, 2), near(l$intercept, -1), near(l$predicted_values, c(1,3,5,7,9)))
stopifnot(near(rsi(1:8, 3)[4:8], rep(100,5)))
stopifnot(near(rsi(rep(5,8), 3)[4:8], rep(50,5)))
x <- stoch_rsi(c(45,50,48,55,52,49,58,60,65,62,68,66,71,69,73,74,70,76,79,77), 5, 3, 3)
stopifnot(all(is.na(x$k_line) | (x$k_line >= 0 & x$k_line <= 1)), length(x$d_line) == 20)
stopifnot(identical(crossover(c(1,3,4,2), c(2,2,3,3)), c('None','Up','None','Down')))
stopifnot(identical(crossunder(c(1,3,4,2), c(2,2,3,3)), c('None','False','False','True')))
cat('All checks passed.\n')
